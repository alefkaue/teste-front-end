import { expect, test, type Page } from '@playwright/test'

const showcase = (page: Page) => page.getByRole('region', { name: 'Vitrine de produtos', exact: true })

test('página completa mantém a composição da referência em 1440px', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  await expect(showcase(page).getByRole('article')).toHaveCount(4)
  await page.evaluate(() => document.fonts.ready)
  const hero = await page.locator('.hero').boundingBox()
  expect(hero?.y).toBe(144)
  expect(hero?.height).toBe(390)
  const card = await showcase(page).getByRole('article').first().boundingBox()
  expect(card?.x).toBeCloseTo(84, 0)
  expect(card?.y).toBeCloseTo(947, 0)
  expect(card?.height).toBe(500)
  await expect(page.getByRole('region', { name: 'Vitrine de destaques', exact: true })).toBeAttached()
  await expect(page.getByRole('region', { name: 'Mais produtos', exact: true })).toBeAttached()
  await expect(page.locator('.partner-card')).toHaveCount(4)
  await expect(page.locator('.brands li')).toHaveCount(5)
  await expect(page.getByRole('navigation', { name: 'Informações institucionais' })).toBeAttached()
  await expect(showcase(page).locator('.product-card__buy').first()).toHaveCSS('background-color', 'rgb(52, 66, 181)')
})

