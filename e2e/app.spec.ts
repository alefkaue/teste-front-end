test('detalhes, favoritos e carrinho sobrevivem ao reload', async ({ page }) => {
  await page.goto('/')
  await showcase(page).getByRole('button', { name: 'Comprar Iphone 11 PRO MAX BRANCO 1', exact: true }).click()
  await page.getByRole('link', { name: 'Ver detalhes', exact: true }).click()
  await expect(page).toHaveURL(/\/produto\/iphone-11-pro-max-branco-1-/)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Iphone 11 PRO MAX BRANCO 1')
  await page.getByRole('button', { name: 'Adicionar aos favoritos' }).click()
  await page.getByRole('button', { name: 'Aumentar quantidade de produto' }).click()
  await page.getByRole('button', { name: 'ADICIONAR AO CARRINHO' }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Remover dos favoritos' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('link', { name: 'Carrinho (2)' }).click()
  await expect(page.getByRole('spinbutton')).toHaveValue('2')
  await expect(page.getByRole('complementary')).toContainText('R$ 30.000,00')
  await page.getByRole('button', { name: /^Aumentar quantidade/ }).click()
  await expect(page.getByRole('complementary')).toContainText('R$ 45.000,00')
  await page.reload()
  await expect(page.getByRole('spinbutton')).toHaveValue('3')
  await page.getByRole('button', { name: /^Remover .* do carrinho/ }).click()
  await expect(page.getByText('Seu carrinho está vazio', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Favoritos', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  await page.getByRole('button', { name: /^Comprar / }).click()
  await page.getByRole('link', { name: 'Ver detalhes', exact: true }).click()
  await page.getByRole('button', { name: 'Remover dos favoritos' }).click()
  await page.getByRole('link', { name: 'Favoritos', exact: true }).click()
  await expect(page.getByText('Nenhum produto encontrado', { exact: true })).toBeVisible()
})

test('trata falha de carregamento, tenta novamente e substitui imagens quebradas', async ({ page }) => {
  await page.route('**/data/produtos.json', route => route.fulfill({ status: 503, body: '' }))
  await page.goto('/')
  await expect(page.getByRole('alert')).toBeVisible()
  await page.unroute('**/data/produtos.json')
  await page.route('**/foto-iphone.png', route => route.abort())
  await page.getByRole('button', { name: 'Tentar novamente' }).click()
  await expect(showcase(page).getByRole('article')).toHaveCount(4)
  await expect(showcase(page).getByRole('img', { name: /^Imagem indisponível/ })).toHaveCount(4)
})

