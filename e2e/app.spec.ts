test('carrossel chega ao fim, volta e funciona com teclado', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await expect(showcase(page).getByRole('article')).toHaveCount(4)
  const next = showcase(page).getByRole('button', { name: 'Próximos produtos' })
  const previous = showcase(page).getByRole('button', { name: 'Produtos anteriores' })
  await expect(previous).toBeDisabled()
  for (let i = 0; i < 6; i++) await next.click()
  await expect(next).toBeDisabled()
  await expect(showcase(page).getByRole('article').last()).toHaveAttribute('aria-label', 'IPHONE 13 MINI 5')
  await expect(showcase(page).getByRole('article').last()).toBeInViewport()
  await previous.click()
  await previous.press('ArrowLeft')
  await expect(showcase(page).getByRole('article').first()).toHaveAttribute('aria-label', 'Iphone 11 PRO MAX BRANCO 3')
})

test('modal usa o produto correto, contém foco, fecha e restaura o foco', async ({ page }) => {
  await page.goto('/')
  const trigger = showcase(page).getByRole('button', { name: 'Comprar IPHONE 13 MINI 1', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('heading')).toHaveText('IPHONE 13 MINI 1')
  await expect(dialog).toContainText('R$ 9.000,00')
  await expect(dialog.getByRole('img')).toHaveAttribute('alt', 'IPHONE 13 MINI 1')
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('hidden')
  await expect(dialog.getByRole('button', { name: 'Fechar produto' })).toBeFocused()
  for (let i = 0; i < 5; i++) {
    await page.keyboard.press('Tab')
    expect(await dialog.evaluate(el => el.contains(document.activeElement))).toBe(true)
  }
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(trigger).toBeFocused()
  await trigger.press('Enter')
  await page.getByRole('button', { name: 'Fechar produto' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await trigger.click()
  await page.mouse.click(8, 8)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('')
})

